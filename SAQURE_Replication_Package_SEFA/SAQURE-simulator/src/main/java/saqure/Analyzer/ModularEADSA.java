/**
 * EADSA on the AED modules, used by RQ1-RQ3.
 *
 * <p>Every exposed CVE contributes its attack-path modules (SAQURE-simulator/AED/modules,
 * generated by build_modules.py): the implementation's AEDI is projected onto
 * each module, every (module, STRIDE target) pair is planned separately, and the cheapest plan
 * per target is kept. The risk of that plan is computed exactly as EADSA computes it.
 *
 * <p>Projection keeps all objects and every init fact whose predicate or function the module
 * declares. A module that does not declare a target's STRIDE predicate cannot reach that
 * target, so the pair is skipped without calling the planner. The AEDI files and the lookup
 * table are read on every assessment, so runtime changes applied to them by
 * {@link PrismModelChecker#update_AED_AEDI} are seen; the matching change of action costs in
 * the modules is applied by {@link #applyExternalChange}.
 *
 * <p>Parallel or sequential computation follows {@link EADSA}: in parallel mode the planner
 * calls share one worker per core (see {@link #POOL_SIZE}), in sequential mode they run one
 * after another.
 * Either way the six STRIDE risks are summed in the order EADSA sums them.
 */
@Slf4j
public final class ModularEADSA {

    private static final String[] STRIDE_FILES = {
            "spoofing.pddl", "tampering.pddl", "repudiation.pddl",
            "information_disclosure.pddl", "denial_of_service.pddl", "elevation_of_privilege.pddl"
    };

    // The action whose success probability changes in RQ2/RQ3 S3; see
    // PrismModelChecker.update_AED_AEDI (AED_ACTION_COST_ORDERING).
    private static final String S3_ACTION = "user-inputs-sensitive-information-in-the-webpage";
    private static final double S3_PUC_T1 = 0.005;
    private static final double S3_PUC_T2 = 0.0;

    private static final Pattern STEP = Pattern.compile("(?:step\\s+)?\\d+:\\s+([A-Za-z0-9\\-]+)(?:\\s|$)");
    private static final Pattern ENTRY = Pattern.compile("(APPLICATION-EXPOSES-ATTACK[^\\s]*)");
    private static final Pattern COST = Pattern.compile("plan cost:\\s*([\\d.]+)", Pattern.CASE_INSENSITIVE);
    private static final Pattern ACTION_KEY = Pattern.compile("\\(:action\\s+(\\S+)", Pattern.CASE_INSENSITIVE);
    private static final Pattern GOAL = Pattern.compile("\\(:goal\\s*\\(and\\s*\\(\\s*([a-zA-Z][\\w-]*)\\s+[^()\\s]+\\s*\\)\\s*\\)");
    private static final Pattern FACT_HEAD = Pattern.compile("^\\(\\s*(?:not\\s*\\(\\s*)?(?:=\\s*\\(\\s*)?([a-zA-Z][\\w-]*)");
    private static final Pattern DECLARATION = Pattern.compile("\\(([^()]*)\\)");

    /**
     * Risk assessment is on the runtime decision path, so the pool is sized for speed. A module
     * planner call takes a few milliseconds, so more workers keep paying off well past EADSA's
     * six: on the 12-core development machine one assessment took 226 ms with 6 workers and
     * 203-211 ms with 8 to 12 (three implementations, median of 9). One worker per core sits on
     * that plateau on any machine; {@code -Dsaqure.modular.threads} overrides it.
     */
    private static final int POOL_SIZE = resolvePoolSize();

    private static int resolvePoolSize() {
        String configured = System.getProperty("saqure.modular.threads");
        if (configured == null || configured.isBlank()) {
            return Math.max(1, Runtime.getRuntime().availableProcessors());
        }
        int requested = Integer.parseInt(configured.trim());
        if (requested < 1) {
            throw new IllegalArgumentException("saqure.modular.threads must be >= 1, but was " + requested);
        }
        return requested;
    }

    private static final ThreadPoolExecutor EXECUTOR = new ThreadPoolExecutor(
            POOL_SIZE, POOL_SIZE, 1, TimeUnit.SECONDS, new LinkedBlockingQueue<>(),
            r -> {
                Thread t = new Thread(r, "modular-eadsa");
                t.setDaemon(true);
                return t;
            });

    /** Projected problems are scratch files; each assessment writes into its own subdirectory. */
    private static final Path WORK_DIR = createWorkDir();
    private static final AtomicInteger ASSESSMENTS = new AtomicInteger();

    /** Declared predicates and functions per module file; costs may change, declarations do not. */
    private static final Map<Path, Set<String>> DECLARED = new ConcurrentHashMap<>();

    private ModularEADSA() {}

    private record Module(String cve, String ap, Path domain, Set<String> declared) {}

    private record Aedi(String head, List<String> facts, String tail, String goal) {}

    private record Plan(double cost, String output) {}

    private record Lookup(Map<String, Double> puc, Map<String, Double> ppre, Map<String, Double> cvss) {}

    // ── Entry points ─────────────────────────────────────────────────────────

    /**
     * RQ1: the default AEDI, with the attack paths written where
     * {@code EADSA.planner_command_configuration_*} writes them.
     *
     * @param scenario e.g. {@code S1_R0_O0_D0_P0}
     */
    public static double configuration(String scenario, String[] cveIds) {
        String out = FilePathConstants.AP_path_RQ1 + scenario + "_plan/";
        return computeScenario(cveIds, FilePathConstants.AEDI_path, new EADSA.outputPath(
                out + "spoofing_plan.pddl",
                out + "tampering_plan.pddl",
                out + "repudiation_plan.pddl",
                out + "information_disclosure_plan.pddl",
                out + "denial_of_service_plan.pddl",
                out + "elevation_of_privilege_plan.pddl"));
    }

    /**
     * RQ2/RQ3: the implementation's own AEDI, with the attack paths written where
     * {@code EADSA.planner_command_compute_RQ2_*} writes them.
     *
     * @param apDirectory   e.g. {@code S1_R0}, under AP/RQ2
     * @param aediDirectory e.g. {@code RQ2/S1/Restaurant_1_service/}, under AEDI
     */
    public static double compute_RQ2(String apDirectory, String aediDirectory, String[] cveIds) {
        String out = FilePathConstants.AP_path_RQ2 + apDirectory + "/";
        return computeScenario(cveIds, FilePathConstants.AEDI_path + aediDirectory, new EADSA.outputPath(
                out + "spoofing.pddl",
                out + "tampering.pddl",
                out + "repudiation.pddl",
                out + "information_disclosure.pddl",
                out + "denial_of_service.pddl",
                out + "elevation_of_privilege.pddl"));
    }

    /**
     * Risk assessment of one implementation: the sum of the six STRIDE risks.
     *
     * @param cveIds        the CVEs the implementation exposes; duplicates are ignored
     * @param aediDirectory directory holding the six STRIDE AEDI files of the implementation
     */
    public static double computeScenario(String[] cveIds, String aediDirectory, EADSA.outputPath path) {
        // One call = the risk assessment of one implementation, which the runtime
        // decision time includes. See RiskTiming.
        Instant riskStart = Instant.now();
        try {
            boolean nodyPa = !EADSA.IS_DEFAULT;
            Lookup lookup = loadLookup(nodyPa ? FilePathConstants.LookupFilePathPath_nodyPa : FilePathConstants.LookupFilePath);
            List<Module> modules = modulesFor(cveIds, Paths.get(nodyPa ? FilePathConstants.ModulesPath_nodyPa : FilePathConstants.ModulesPath));
            Path aediDir = Paths.get(aediDirectory);
            Path work = WORK_DIR.resolve(Integer.toString(ASSESSMENTS.incrementAndGet()));

            // Project the AEDI onto every module that can reach the target.
            List<List<Callable<Plan>>> calls = new ArrayList<>();
            for (String strideFile : STRIDE_FILES) {
                Aedi aedi = readAedi(aediDir.resolve(strideFile));
                List<Callable<Plan>> perTarget = new ArrayList<>();
                for (Module m : modules) {
                    if (!m.declared().contains(aedi.goal())) {
                        continue;
                    }
                    Path problem = work.resolve(m.cve()).resolve(m.ap()).resolve(strideFile);
                    Files.createDirectories(problem.getParent());
                    Files.writeString(problem, project(aedi, m.declared()));
                    perTarget.add(() -> runPlanner(m.domain(), problem));
                }
                calls.add(perTarget);
            }

            List<List<Plan>> plans = EADSA.isParallel() ? runParallel(calls) : runSequential(calls);

            String[] outputs = {path.spoofingPath, path.tamperingPath, path.repudiationPath,
                    path.infoDisclosurePath, path.denialOfServicePath, path.elevationOfPrivilegePath};
            double[] risks = new double[STRIDE_FILES.length];
            for (int i = 0; i < STRIDE_FILES.length; i++) {
                Plan best = null;
                for (Plan p : plans.get(i)) {
                    if (p != null && (best == null || p.cost() < best.cost())) {
                        best = p;
                    }
                }
                risks[i] = best == null ? 0.0 : risk(best.output(), lookup);
                writePlan(outputs[i], best == null
                        ? "; No vulnerability module reaches this target: no attack path.\n"
                        : best.output());
            }
            // EADSA's parallel path sums with DoubleStream.sum, its sequential path left to right.
            return EADSA.isParallel()
                    ? DoubleStream.of(risks).sum()
                    : risks[0] + risks[1] + risks[2] + risks[3] + risks[4] + risks[5];
        } catch (IOException e) {
            throw new UncheckedIOException("Modular risk assessment failed for " + aediDirectory, e);
        } finally {
            RiskTiming.record(Duration.between(riskStart, Instant.now()));
        }
    }

    // ── Runtime changes ──────────────────────────────────────────────────────

    /**
     * Applies to the modules the part of a runtime change that lives in the AED. AEDI changes
     * need nothing here, because every assessment projects the current AEDI files.
     */
    public static void applyExternalChange(PrismModelChecker.ExternalChanges change) {
        if (change == PrismModelChecker.ExternalChanges.AED_ACTION_COST_ORDERING) {
            changeActionCost(S3_ACTION, S3_PUC_T1, S3_PUC_T2);
        }
    }

    /** Undoes {@link #applyExternalChange}. */
    public static void reverseExternalChange(PrismModelChecker.ExternalChanges change) {
        if (change == PrismModelChecker.ExternalChanges.AED_ACTION_COST_ORDERING) {
            changeActionCost(S3_ACTION, S3_PUC_T2, S3_PUC_T1);
        }
    }

    /**
     * Rewrites the cost of {@code action} in every default module that contains it, with the
     * same cost formula as PrismModelChecker.changeActionCost_AED, which changes the default
     * AED file and the lookup table only.
     */
    private static void changeActionCost(String action, double originalPuc, double newPuc) {
        String originalCost = Integer.toString(actionCost(originalPuc));
        String newCost = Integer.toString(actionCost(newPuc));
        Pattern header = Pattern.compile("\\(:action\\s+" + Pattern.quote(action) + "(\\s|$)", Pattern.CASE_INSENSITIVE);
        try (Stream<Path> files = Files.walk(Paths.get(FilePathConstants.ModulesPath))) {
            for (Path module : files.filter(p -> p.toString().endsWith(".pddl")).sorted().toList()) {
                List<String> lines = Files.readAllLines(module);
                boolean changed = false;
                for (int i = 0; i < lines.size(); i++) {
                    if (!header.matcher(lines.get(i)).find()) {
                        continue;
                    }
                    for (int j = i; j < lines.size(); j++) {
                        if (lines.get(j).toLowerCase().contains("total-cost")) {
                            lines.set(j, lines.get(j).replace(originalCost, newCost));
                            changed = true;
                            break;
                        }
                    }
                }
                if (changed) {
                    Files.write(module, lines);
                }
            }
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot change the cost of " + action + " in the modules", e);
        }
    }

    private static int actionCost(double puc) {
        return (int) Math.ceil(Math.max(1.0, -100.0 * Math.log(Math.max(1e-6, puc))));
    }

    // ── Modules and projection ───────────────────────────────────────────────

    private static List<Module> modulesFor(String[] cveIds, Path root) throws IOException {
        Set<String> cves = new LinkedHashSet<>();
        for (String cve : cveIds) {
            cves.add(cve.trim());
        }
        List<Module> modules = new ArrayList<>();
        for (String cve : cves) {
            Path dir = root.resolve(cve);
            if (!Files.isDirectory(dir)) {
                log.warn("No vulnerability module for {}", cve);
                continue;
            }
            try (Stream<Path> aps = Files.list(dir)) {
                for (Path domain : aps.filter(p -> p.toString().endsWith(".pddl"))
                        .sorted(Comparator.comparing(p -> p.getFileName().toString())).toList()) {
                    String ap = domain.getFileName().toString().replace(".pddl", "");
                    modules.add(new Module(cve, ap, domain, DECLARED.computeIfAbsent(domain, ModularEADSA::declaredSymbols)));
                }
            }
        }
        return modules;
    }

    private static Set<String> declaredSymbols(Path domain) {
        try {
            String text = stripComments(Files.readString(domain));
            Set<String> symbols = new HashSet<>();
            symbols.add("total-cost");
            for (String section : List.of("(:predicates", "(:functions")) {
                int start = text.indexOf(section);
                if (start < 0) {
                    continue;
                }
                Matcher m = DECLARATION.matcher(text.substring(start + section.length(), balanced(text, start) - 1));
                while (m.find()) {
                    String[] tokens = m.group(1).trim().split("\\s+");
                    if (!tokens[0].isEmpty()) {
                        symbols.add(tokens[0].toLowerCase());
                    }
                }
            }
            return symbols;
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot read module " + domain, e);
        }
    }

    private static Aedi readAedi(Path file) throws IOException {
        String text = stripComments(Files.readString(file));
        int start = text.indexOf("(:init");
        int end = balanced(text, start);
        List<String> facts = new ArrayList<>();
        String body = text.substring(start + "(:init".length(), end - 1);
        for (int k = body.indexOf('('); k >= 0; k = body.indexOf('(', k)) {
            int close = balanced(body, k);
            facts.add(body.substring(k, close).replaceAll("\\s+", " "));
            k = close;
        }
        String tail = text.substring(end);
        Matcher goal = GOAL.matcher(tail);
        if (!goal.find()) {
            throw new IllegalStateException("Expected a goal of the form (:goal (and (<stride> <app>))) in " + file);
        }
        return new Aedi(text.substring(0, start), facts, tail, goal.group(1).toLowerCase());
    }

    /** Keeps all objects and every init fact whose predicate or function the module declares. */
    private static String project(Aedi aedi, Set<String> declared) {
        StringBuilder sb = new StringBuilder(aedi.head()).append("(:init\n");
        for (String fact : aedi.facts()) {
            Matcher m = FACT_HEAD.matcher(fact);
            if (m.find() && declared.contains(m.group(1).toLowerCase())) {
                sb.append("    ").append(fact).append('\n');
            }
        }
        return sb.append("  )").append(aedi.tail()).toString();
    }

    private static String stripComments(String text) {
        return text.replaceAll("(?m);.*$", "");
    }

    private static int balanced(String text, int start) {
        int depth = 0;
        for (int k = start; k < text.length(); k++) {
            char c = text.charAt(k);
            if (c == '(') {
                depth++;
            } else if (c == ')' && --depth == 0) {
                return k + 1;
            }
        }
        throw new IllegalStateException("Unbalanced parentheses from offset " + start);
    }

    // ── Planning ─────────────────────────────────────────────────────────────

    private static List<List<Plan>> runParallel(List<List<Callable<Plan>>> calls) {
        List<List<Future<Plan>>> futures = new ArrayList<>();
        for (List<Callable<Plan>> perTarget : calls) {
            List<Future<Plan>> f = new ArrayList<>();
            for (Callable<Plan> c : perTarget) {
                f.add(EXECUTOR.submit(c));
            }
            futures.add(f);
        }
        List<List<Plan>> plans = new ArrayList<>();
        for (List<Future<Plan>> perTarget : futures) {
            List<Plan> p = new ArrayList<>();
            for (Future<Plan> f : perTarget) {
                try {
                    p.add(f.get());
                } catch (InterruptedException e) {
                    Thread.currentThread().interrupt();
                    throw new IllegalStateException("Interrupted while planning", e);
                } catch (ExecutionException e) {
                    throw new IllegalStateException("Planner call failed", e.getCause());
                }
            }
            plans.add(p);
        }
        return plans;
    }

    private static List<List<Plan>> runSequential(List<List<Callable<Plan>>> calls) {
        List<List<Plan>> plans = new ArrayList<>();
        for (List<Callable<Plan>> perTarget : calls) {
            List<Plan> p = new ArrayList<>();
            for (Callable<Plan> c : perTarget) {
                try {
                    p.add(c.call());
                } catch (Exception e) {
                    throw new IllegalStateException("Planner call failed", e);
                }
            }
            plans.add(p);
        }
        return plans;
    }

    /** One Metric-FF call, with EADSA's options; {@code null} when the target is unreachable. */
    private static Plan runPlanner(Path domain, Path problem) throws IOException, InterruptedException {
        ProcessBuilder pb = new ProcessBuilder(
                FilePathConstants.FFPath,
                "-o", domain.toString(),
                "-f", problem.toString(),
                "-s", "4",
                "-w", "1");
        pb.redirectErrorStream(true);
        Process process = pb.start();
        String output = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8);
        process.waitFor();
        if (!output.contains("found legal plan")) {
            return null;
        }
        Matcher m = COST.matcher(output);
        return new Plan(m.find() ? Double.parseDouble(m.group(1)) : Double.MAX_VALUE, output);
    }

    // ── Risk, as EADSA.attack_path_risk_compute ──────────────────────────────

    private static Lookup loadLookup(String file) throws IOException {
        ObjectMapper mapper = new ObjectMapper();
        mapper.configure(com.fasterxml.jackson.core.JsonParser.Feature.ALLOW_NON_NUMERIC_NUMBERS, true);
        List<Map<String, Object>> entries = mapper.readValue(new File(file), new TypeReference<List<Map<String, Object>>>() {});
        Map<String, Double> puc = new HashMap<>();
        Map<String, Double> ppre = new HashMap<>();
        Map<String, Double> cvss = new HashMap<>();
        for (Map<String, Object> entry : entries) {
            Object actionList = entry.get("Action List");
            Matcher m = ACTION_KEY.matcher(actionList == null ? "" : actionList.toString());
            if (!m.find()) {
                continue;
            }
            String key = m.group(1).toLowerCase();
            puc.put(key, number(entry.get("Puc"), 1.0));
            ppre.put(key, number(entry.get("Ppre"), 1.0));
            cvss.put(key, number(entry.get("CVSS"), 0.0));
        }
        return new Lookup(puc, ppre, cvss);
    }

    private static double number(Object value, double fallback) {
        if (value instanceof Number n) {
            double v = n.doubleValue();
            return Double.isNaN(v) ? fallback : v;
        }
        return fallback;
    }

    /** CVSS of the entry action times Ppre*Puc of every step, in EADSA's arithmetic order. */
    private static double risk(String plannerOutput, Lookup lookup) {
        double weightedRisk = 1.0;
        boolean entryCvssApplied = false;
        for (String line : plannerOutput.split("\n")) {
            Matcher m = STEP.matcher(line);
            if (!m.find()) {
                continue;
            }
            String action = m.group(1).toLowerCase();
            double probA = lookup.ppre().getOrDefault(action, 1.0) * lookup.puc().getOrDefault(action, 1.0);
            if (ENTRY.matcher(line).find() && !entryCvssApplied) {
                entryCvssApplied = true;
                weightedRisk = lookup.cvss().getOrDefault(action, 0.0) * probA * weightedRisk;
            } else {
                weightedRisk = probA * weightedRisk;
            }
        }
        return weightedRisk == 1 ? 0 : weightedRisk;
    }

    // ── Files ────────────────────────────────────────────────────────────────

    private static void writePlan(String outputFile, String content) throws IOException {
        Path target = Paths.get(outputFile);
        if (target.getParent() != null) {
            Files.createDirectories(target.getParent());
        }
        Files.writeString(target, content);
    }

    private static Path createWorkDir() {
        try {
            Path dir = Files.createTempDirectory("saqure-modules-");
            Runtime.getRuntime().addShutdownHook(new Thread(() -> deleteRecursively(dir)));
            return dir;
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot create the projection directory", e);
        }
    }

    private static void deleteRecursively(Path dir) {
        try (Stream<Path> files = Files.walk(dir)) {
            files.sorted(Comparator.reverseOrder()).forEach(p -> p.toFile().delete());
        } catch (IOException ignored) {
            // Best effort: the files are scratch copies under the system temp directory.
        }
    }
}
