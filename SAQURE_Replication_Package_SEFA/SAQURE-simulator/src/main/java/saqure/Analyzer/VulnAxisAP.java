package saqure.Analyzer;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import lombok.extern.slf4j.Slf4j;
import saqure.utils.FilePathConstants;

import java.io.BufferedReader;
import java.io.File;
import java.io.InputStreamReader;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.time.Duration;
import java.time.Instant;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ExecutorService;
import java.util.concurrent.Executors;
import java.util.concurrent.Future;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Collectors;
import java.util.stream.Stream;

/**
 * Attack-path generation for the RQ4 vulnerability axis (1-100 vulnerabilities).
 *
 * <p>The attack-path specification of every exposed vulnerability is planned against every
 * STRIDE AEDI, and the cheapest solvable plan per target is kept. The
 * (domain, problem) pairs are pre-generated by scripts/prepare_all.py, so only the
 * planner calls and the selection happen here.
 *
 * <p>The scenario cost keeps EADSA's definition: the sum of the six STRIDE risks, where a
 * path's risk is CVSS(entry) multiplied by Ppre*Puc of every step.
 */
@Slf4j
public class VulnAxisAP {

    public static final String[] STRIDES = {
            "spoofing", "tampering", "repudiation",
            "information-disclosure", "denial-of-service", "elevation-of-privilege"
    };

    private static final Pattern STEP = Pattern.compile("(?:step\\s+)?\\d+:\\s+([A-Za-z0-9\\-]+)(?:\\s|$)");
    private static final Pattern ENTRY = Pattern.compile("(APPLICATION-EXPOSES-ATTACK[^\\s]*)");
    private static final Pattern COST = Pattern.compile("plan cost:\\s*([\\d.]+)", Pattern.CASE_INSENSITIVE);
    private static final Pattern ACTION_KEY = Pattern.compile("\\(:action\\s+(\\S+)", Pattern.CASE_INSENSITIVE);

    private static Map<String, double[]> lookup;   // action -> {CVSS, Ppre, Puc}

    /**
     * Planner calls run concurrently on one thread per core by default. The
     * {@code saqure.vulnaxis.threads} system property overrides it, which is how the
     * serial baseline and the speedup curve are measured; experiments that do not set
     * it are unaffected.
     */
    static int poolSize() {
        String configured = System.getProperty("saqure.vulnaxis.threads");
        if (configured == null || configured.isBlank()) {
            return Math.max(1, Runtime.getRuntime().availableProcessors());
        }
        int requested = Integer.parseInt(configured.trim());
        if (requested < 1) {
            throw new IllegalArgumentException("saqure.vulnaxis.threads must be >= 1, but was " + requested);
        }
        return requested;
    }

    /** One planner result: which AP produced it, what it cost, and the plan text. */
    private record PlanResult(String cve, String ap, String stride, double cost, String output) {}

    // ── Lookup table ─────────────────────────────────────────────────────────

    private static synchronized Map<String, double[]> lookup() {
        if (lookup != null) {
            return lookup;
        }
        Map<String, double[]> map = new HashMap<>();
        try {
            ObjectMapper mapper = new ObjectMapper();
            mapper.configure(com.fasterxml.jackson.core.JsonParser.Feature.ALLOW_NON_NUMERIC_NUMBERS, true);
            List<Map<String, Object>> entries = mapper.readValue(
                    new File(FilePathConstants.LookupFilePathExtended),
                    new TypeReference<List<Map<String, Object>>>() {});
            for (Map<String, Object> e : entries) {
                Object al = e.get("Action List");
                if (al == null) {
                    continue;
                }
                Matcher m = ACTION_KEY.matcher(al.toString());
                if (!m.find()) {
                    continue;
                }
                map.put(m.group(1).toLowerCase(),
                        new double[]{num(e.get("CVSS"), 0.0), num(e.get("Ppre"), 1.0), num(e.get("Puc"), 1.0)});
            }
        } catch (Exception e) {
            log.error("Failed to read extended lookup file: {}", e.getMessage());
        }
        lookup = map;
        return lookup;
    }

    private static double num(Object o, double fallback) {
        if (o instanceof Number n) {
            double v = n.doubleValue();
            return Double.isNaN(v) ? fallback : v;
        }
        return fallback;
    }

    // ── Steps 1-2: the domains of the exposed CVEs ───────────────────────────

    private static List<Path> selectDomains(String[] cveIds) {
        List<Path> dirs = new ArrayList<>();
        for (String cve : cveIds) {
            Path base = Paths.get(FilePathConstants.PreparedAPPath, cve.trim());
            if (!Files.isDirectory(base)) {
                log.warn("No prepared domain for {}", cve);
                continue;
            }
            try (Stream<Path> s = Files.list(base)) {
                dirs.addAll(s.filter(Files::isDirectory).sorted().collect(Collectors.toList()));
            } catch (Exception e) {
                log.error("Cannot list {}: {}", base, e.getMessage());
            }
        }
        return dirs;
    }

    // ── Steps 4-5: plan on every pair, keep the cheapest per STRIDE ──────────

    /**
     * Runs the M x 6 planner calls and returns the summed risk of the six selected paths.
     *
     * @param cveIds the CVEs exposed by this implementation
     */
    public static double computeScenario(String[] cveIds) {
        // One call = the risk assessment of one implementation, which the runtime
        // decision time now includes. See RiskTiming.
        Instant riskStart = Instant.now();
        List<Path> apDirs = selectDomains(cveIds);
        ExecutorService pool = Executors.newFixedThreadPool(poolSize());
        List<Future<PlanResult>> futures = new ArrayList<>();
        try {
            for (Path apDir : apDirs) {
                String ap = apDir.getFileName().toString();
                String cve = apDir.getParent().getFileName().toString();
                Path domain = apDir.resolve("domain.pddl");
                for (String stride : STRIDES) {
                    Path problem = apDir.resolve(stride + ".pddl");
                    futures.add(pool.submit(() -> runPlanner(cve, ap, stride, domain, problem)));
                }
            }

            Map<String, PlanResult> best = new HashMap<>();
            for (Future<PlanResult> f : futures) {
                PlanResult r;
                try {
                    r = f.get();
                } catch (Exception e) {
                    continue;
                }
                if (r == null) {
                    continue;
                }
                PlanResult cur = best.get(r.stride());
                if (cur == null || r.cost() < cur.cost()) {
                    best.put(r.stride(), r);
                }
            }

            double total = 0.0;
            for (String stride : STRIDES) {
                PlanResult r = best.get(stride);
                if (r != null) {
                    total += risk(r.output());
                }
            }
            return total;
        } finally {
            pool.shutdown();
            RiskTiming.record(Duration.between(riskStart, Instant.now()));
        }
    }

    /**
     * Loads the lookup table up front. {@link #lookup()} is lazy and is first reached from
     * {@link #risk}, which would charge its one-off JSON parse to whichever implementation
     * happens to be assessed first. Call this before a measured pass.
     */
    public static void warmUpLookup() {
        lookup();
    }

    private static PlanResult runPlanner(String cve, String ap, String stride, Path domain, Path problem) {
        try {
            ProcessBuilder pb = new ProcessBuilder(
                    FilePathConstants.FFPath,
                    "-o", domain.toString(),
                    "-f", problem.toString(),
                    "-s", "4",
                    "-w", "1");
            pb.redirectErrorStream(true);
            Process p = pb.start();
            StringBuilder sb = new StringBuilder();
            try (BufferedReader br = new BufferedReader(new InputStreamReader(p.getInputStream()))) {
                String line;
                while ((line = br.readLine()) != null) {
                    sb.append(line).append('\n');
                }
            }
            p.waitFor();
            String out = sb.toString();
            if (!out.contains("found legal plan")) {
                return null;       // this domain cannot reach this STRIDE target
            }
            Matcher m = COST.matcher(out);
            double cost = m.find() ? Double.parseDouble(m.group(1)) : Double.MAX_VALUE;
            return new PlanResult(cve, ap, stride, cost, out);
        } catch (Exception e) {
            log.error("Planner failed for {}/{} {}: {}", cve, ap, stride, e.getMessage());
            return null;
        }
    }

    /** EADSA's risk definition: CVSS of the entry action times Ppre*Puc of every step. */
    private static double risk(String plannerOutput) {
        Map<String, double[]> table = lookup();
        double weighted = 1.0;
        // Eq.(1) multiplies the CVSS of *the* entry action once; a plan that mentions a second
        // APPLICATION-EXPOSES-ATTACK line must not multiply another CVSS on top of it.
        boolean entryCvssApplied = false;
        for (String line : plannerOutput.split("\n")) {
            Matcher m = STEP.matcher(line);
            if (!m.find()) {
                continue;
            }
            String action = m.group(1).toLowerCase();
            double[] v = table.getOrDefault(action, new double[]{0.0, 1.0, 1.0});
            double probA = v[1] * v[2];
            boolean isEntry = ENTRY.matcher(line).find() && !entryCvssApplied;
            if (isEntry) {
                entryCvssApplied = true;
                weighted = v[0] * probA * weighted;
            } else {
                weighted = probA * weighted;
            }
        }
        return weighted == 1.0 ? 0.0 : weighted;
    }

    private VulnAxisAP() {}
}
